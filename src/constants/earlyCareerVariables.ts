const theaterYears = Array.from(new Set(theaterCredits.map((credit) => credit.year))).sort().reverse()

const DALENBERG_NOTE = "Credited as Ann-Marie Dalenberg"

const theaterCreditEntries: EarlyCareerRole[] = theaterYears.flatMap((year, yearIndex) =>
  theaterCredits
    .filter((credit) => credit.year === year)
    .map((credit, creditIndex) => {
      const isFirstOverall = yearIndex === 0 && creditIndex === 0
      const notes = [isFirstOverall ? DALENBERG_NOTE : null, credit.note ?? null].filter(Boolean)

      return {
        role: credit.show,
        company: `${credit.venue} — ${credit.role}`,
        dates: credit.year,
        bullets: credit.soundDesigner ? [`Sound design: ${credit.soundDesigner}`] : [],
        ...(notes.length > 0 ? { note: notes.join(" ") } : {}),
      }
    })
)

